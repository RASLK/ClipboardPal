    private static Dictionary<string, string> Merge(
        Dictionary<string, string> baseline,
        Dictionary<string, string> overlay)
    {
        var map = new Dictionary<string, string>(baseline, StringComparer.Ordinal);
        foreach (var (k, v) in overlay)
            map[k] = v;
        return map;
    }
