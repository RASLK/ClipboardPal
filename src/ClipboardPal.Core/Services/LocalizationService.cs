/// <summary>Bindable indexer wrapper that refreshes when the UI language changes.</summary>
public sealed class LocView : INotifyPropertyChanged
{
    private readonly ILocalizationService _l10n;

    public LocView(ILocalizationService l10n)
    {
        _l10n = l10n;
        _l10n.LanguageChanged += () =>
            PropertyChanged?.Invoke(this, new PropertyChangedEventArgs(string.Empty));
    }

    public string this[string key] => _l10n[key];

    public event PropertyChangedEventHandler? PropertyChanged;
}

public sealed class LocalizationService : ILocalizationService
{
    private Dictionary<string, string> _map = En;

    public event Action? LanguageChanged;

    public string this[string key] =>
        _map.TryGetValue(key, out var v) ? v : En.GetValueOrDefault(key, key);

    public void SetLanguage(UiLanguage language)
    {
        _map = Resolve(language);
        LanguageChanged?.Invoke();
    }

    private static Dictionary<string, string> Resolve(UiLanguage language) => language switch
    {
        UiLanguage.Russian => Ru,
        UiLanguage.German => De,
        UiLanguage.French => Fr,
        UiLanguage.Chinese => Zh,
        UiLanguage.Japanese => Ja,
        _ => En
    };

